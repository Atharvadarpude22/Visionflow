from pathlib import Path
from typing import Optional, Dict, List, Any
from collections import Counter
import json


class DatasetIntelligence:
    """
    Dataset Intelligence for VisionFlow.

    Determines what the dataset actually contains, identifies
    weaknesses/gaps, connects dataset characteristics with model
    performance, estimates additional data requirements, and
    creates a data acquisition plan.

    1. Find dataset gaps
    2. Analyze model errors
    3. Estimate required data
    4. Plan additional data acquisition
    5. Measure dataset impact

    This class does NOT train models.
    """

    def __init__(
        self,
        path=None,
        dataset=None,
        model=None,
        config: Optional[dict] = None
    ):
        self.path = Path(path) if path is not None else None

        self.dataset = dataset
        self.model = model
        self.config = config or {}

        # Configuration
        self.minimum_coverage = self.config.get("minimum_coverage", 0.10)
        self.minimum_performance = self.config.get("minimum_performance", 0.80)
        self.target_performance = self.config.get("target_performance", 0.90)
        self.rare_threshold = self.config.get("rare_threshold", 0.05)
        self.samples_per_gap = self.config.get("samples_per_gap", 100)

        # Result storage
        self.coverage_result = None
        self.error_result = None
        self.gap_result = None
        self.data_estimate_result = None
        self.acquisition_result = None
        self.impact_result = None

    # =========================================================
    # INTERNAL HELPERS
    # =========================================================

    def _get_samples(self) -> List[Dict[str, Any]]:
        """
        Safely obtain dataset samples.

        Looks at dataset.samples, then dataset.preparer.samples,
        then dataset._preparer.samples.
        """

        dataset = self.dataset

        if dataset is None:
            return []

        samples = getattr(dataset, "samples", None)

        if samples is not None:
            return samples

        for name in ("preparer", "_preparer"):

            preparer = getattr(dataset, name, None)

            if preparer is not None:

                samples = getattr(preparer, "samples", None)

                if samples is not None:
                    return samples

        return []

    def _get_dataset_result(
        self,
        name: str
    ):
        """Retrieve results already generated by other dataset components."""

        if self.dataset is None:
            return None

        attribute_map = {
            "analysis": "_analysis_result",
            "preparation": "_preparation_result",
            "optimization": "_optimization_result",
            "gaps": "_gap_result",
        }

        attribute = attribute_map.get(name)

        if attribute is None:
            return None

        return getattr(self.dataset, attribute, None)

    def _safe_number(
        self,
        value,
        default=0.0
    ):
        """Convert a value into a number safely."""

        try:

            if value is None:
                return default

            return float(value)

        except (TypeError, ValueError):

            return default

    def _extract_classes(
        self,
        samples
    ) -> Counter:
        """
        Extract class frequencies from samples.

        Supports {"classes": [...]}, {"class": "x"} or {"label": "x"}.
        """

        counter = Counter()

        for sample in samples:

            if not isinstance(sample, dict):
                continue

            classes = sample.get("classes")

            if classes is None:

                single_class = sample.get("class")

                if single_class is None:
                    single_class = sample.get("label")

                if single_class is not None:
                    classes = [single_class]

            if isinstance(classes, str):
                classes = [classes]

            if isinstance(classes, (list, tuple, set)):

                for class_name in classes:

                    if class_name is not None:
                        counter[str(class_name)] += 1

        return counter

    def _extract_conditions(
        self,
        samples
    ) -> Counter:
        """
        Extract environmental/condition information from fields:
        condition, lighting, weather, environment, scene, time_of_day.
        """

        counter = Counter()

        fields = (
            "condition",
            "lighting",
            "weather",
            "environment",
            "scene",
            "time_of_day"
        )

        for sample in samples:

            if not isinstance(sample, dict):
                continue

            for field in fields:

                value = sample.get(field)

                if value is not None:
                    counter[f"{field}:{value}"] += 1

        return counter

    def _get_model_results(self):
        """
        Try to obtain model evaluation/performance results.

        DatasetIntelligence does not require a model to exist.
        """

        model = self.model

        if model is None:
            return {}

        for attribute in (
            "_evaluation_result",
            "evaluation_result",
            "evaluation",
            "metrics",
            "results"
        ):

            result = getattr(model, attribute, None)

            if isinstance(result, dict):
                return result

        return {}

    # =========================================================
    # FIND GAPS
    # =========================================================

    def find_gaps(
        self,
        model=None,
        performance=None,
        **kwargs
    ) -> Dict[str, Any]:
        """
        Identify important dataset gaps.

        Example: overall recall 93%, small objects 70%, low light 65%
        -> gaps for low_light and small_objects.
        """

        if model is not None:
            self.model = model

        samples = self._get_samples()
        total_samples = len(samples)

        class_counts = self._extract_classes(samples)
        condition_counts = self._extract_conditions(samples)

        if performance is None:
            performance = self._get_model_results()

        if performance is None:
            performance = {}

        # Gaps are collected in priority order in a single pass:
        # performance -> rare classes -> conditions.
        gaps = []

        # -----------------------------------------------------
        # Performance gaps
        # -----------------------------------------------------

        performance_gaps = []

        if isinstance(performance, dict):

            minimum_performance = self.minimum_performance

            for metric, value in performance.items():

                if isinstance(value, (int, float)):

                    numeric_value = float(value)

                    if numeric_value < minimum_performance:

                        performance_gaps.append({
                            "area": metric,
                            "performance": numeric_value,
                            "target": self.target_performance
                        })

                        gaps.append({
                            "type": "model_performance",
                            "area": metric,
                            "performance": numeric_value,
                            "target": self.target_performance,
                            "priority": "HIGH"
                        })

        # -----------------------------------------------------
        # Class coverage and rare classes
        # -----------------------------------------------------

        class_coverage = {}
        rare_classes = []

        if total_samples > 0:

            rare_threshold = self.rare_threshold

            for class_name, count in class_counts.items():

                ratio = round(count / total_samples, 4)

                class_coverage[class_name] = ratio

                if ratio < rare_threshold:

                    rare_classes.append({
                        "class": class_name,
                        "ratio": ratio,
                        "count": count
                    })

                    gaps.append({
                        "type": "rare_class",
                        "area": class_name,
                        "count": count,
                        "coverage": ratio,
                        "priority": "HIGH"
                    })

        # -----------------------------------------------------
        # Condition gaps
        # -----------------------------------------------------

        condition_gaps = []

        if total_samples > 0:

            minimum_coverage = self.minimum_coverage

            for condition, count in condition_counts.items():

                ratio = count / total_samples

                if ratio < minimum_coverage:

                    coverage = round(ratio, 4)

                    condition_gaps.append({
                        "condition": condition,
                        "count": count,
                        "coverage": coverage
                    })

                    gaps.append({
                        "type": "condition",
                        "area": condition,
                        "count": count,
                        "coverage": coverage,
                        "priority": "MEDIUM"
                    })

        self.gap_result = {
            "total_samples": total_samples,
            "class_distribution": dict(class_counts),
            "class_coverage": class_coverage,
            "rare_cases": rare_classes,
            "condition_distribution": dict(condition_counts),
            "performance_gaps": performance_gaps,
            "condition_gaps": condition_gaps,
            "gaps": gaps,
            "gap_count": len(gaps)
        }

        return self.gap_result

    # =========================================================
    # ANALYZE ERRORS
    # =========================================================

    def analyze_errors(
        self,
        errors=None,
        **kwargs
    ) -> Dict[str, Any]:
        """
        Connect model failures with dataset characteristics.

        Each error may contain "class", "condition" and "error".
        Works with an empty error set.
        """

        if errors is None:
            errors = []

        if not isinstance(errors, list):
            errors = [errors]

        by_class = Counter()
        by_condition = Counter()
        by_type = Counter()

        for error in errors:

            if not isinstance(error, dict):
                continue

            class_name = error.get("class")
            condition = error.get("condition")
            error_type = error.get("error")

            if class_name is not None:
                by_class[str(class_name)] += 1

            if condition is not None:
                by_condition[str(condition)] += 1

            if error_type is not None:
                by_type[str(error_type)] += 1

        self.error_result = {
            "total_errors": len(errors),
            "errors_by_class": dict(by_class),
            "errors_by_condition": dict(by_condition),
            "errors_by_type": dict(by_type)
        }

        return self.error_result

    # =========================================================
    # ESTIMATE REQUIRED DATA
    # =========================================================

    def estimate_required_data(
        self,
        gaps=None,
        samples_per_gap=None,
        **kwargs
    ) -> Dict[str, Any]:
        """Estimate how much additional data could be useful."""

        if samples_per_gap is None:
            samples_per_gap = self.samples_per_gap

        if gaps is None:

            if self.gap_result is None:
                self.find_gaps()

            gaps = self.gap_result.get("gaps", [])

        estimates = []
        total_required = 0

        for gap in gaps:

            priority = gap.get("priority", "MEDIUM")

            if priority == "HIGH":
                amount = samples_per_gap * 2

            elif priority == "MEDIUM":
                amount = samples_per_gap

            else:
                amount = samples_per_gap // 2

            total_required += amount

            estimates.append({
                "area": gap.get("area", "unknown"),
                "priority": priority,
                "estimated_additional_samples": amount
            })

        self.data_estimate_result = {
            "estimates": estimates,
            "total_estimated_samples": total_required
        }

        return self.data_estimate_result

    # =========================================================
    # PLAN ACQUISITION
    # =========================================================

    def plan_acquisition(
        self,
        gaps=None,
        **kwargs
    ) -> Dict[str, Any]:
        """Convert identified gaps into a practical data collection plan."""

        if gaps is None:

            if self.gap_result is None:
                self.find_gaps()

            gaps = self.gap_result.get("gaps", [])

        if self.data_estimate_result is None:
            self.estimate_required_data(gaps=gaps)

        plan = []
        total_to_collect = 0

        for estimate in self.data_estimate_result.get("estimates", []):

            area = estimate["area"]
            amount = estimate["estimated_additional_samples"]

            total_to_collect += amount

            plan.append({
                "target": area,
                "priority": estimate["priority"],
                "samples_to_collect": amount,
                "reason": f"Improve dataset coverage for {area}"
            })

        self.acquisition_result = {
            "plan": plan,
            "total_samples_to_collect": total_to_collect
        }

        return self.acquisition_result

    # =========================================================
    # MEASURE IMPACT
    # =========================================================

    def measure_impact(
        self,
        previous_metrics=None,
        current_metrics=None,
        **kwargs
    ) -> Dict[str, Any]:
        """
        Compare model performance before and after a dataset change
        (Dataset V1 -> Model V1 vs Dataset V2 -> Model V2).
        """

        previous_metrics = previous_metrics or {}
        current_metrics = current_metrics or {}

        comparison = {}

        for metric in set(previous_metrics).union(current_metrics):

            previous = self._safe_number(
                previous_metrics.get(metric),
                default=None
            )

            current = self._safe_number(
                current_metrics.get(metric),
                default=None
            )

            if previous is None or current is None:

                comparison[metric] = {
                    "previous": previous,
                    "current": current,
                    "change": None
                }

                continue

            comparison[metric] = {
                "previous": previous,
                "current": current,
                "change": round(current - previous, 6)
            }

        self.impact_result = {
            "previous_metrics": previous_metrics,
            "current_metrics": current_metrics,
            "comparison": comparison
        }

        return self.impact_result

    # =========================================================
    # COMPLETE INTELLIGENCE WORKFLOW
    # =========================================================

    def analyze(
        self,
        model=None,
        performance=None,
        errors=None,
        **kwargs
    ) -> Dict[str, Any]:
        """
        Run the complete workflow:
        find gaps -> analyze errors -> estimate data -> acquisition plan.
        """

        gap_result = self.find_gaps(
            model=model,
            performance=performance
        )

        gaps = gap_result.get("gaps", [])

        error_result = self.analyze_errors(errors=errors)

        estimate_result = self.estimate_required_data(gaps=gaps)

        acquisition_result = self.plan_acquisition(gaps=gaps)

        return {
            "gaps": gap_result,
            "errors": error_result,
            "required_data": estimate_result,
            "acquisition_plan": acquisition_result
        }

    # =========================================================
    # SUMMARY
    # =========================================================

    def summary(self) -> Dict[str, Any]:
        """Return a compact intelligence summary."""

        gap_count = 0

        if self.gap_result is not None:
            gap_count = self.gap_result.get("gap_count", 0)

        total_required = 0

        if self.data_estimate_result is not None:
            total_required = self.data_estimate_result.get(
                "total_estimated_samples",
                0
            )

        return {
            "dataset_exists": (
                self.path.exists() if self.path is not None else False
            ),
            "dataset_path": (
                str(self.path) if self.path is not None else None
            ),
            "model_available": self.model is not None,
            "gaps_detected": gap_count,
            "estimated_required_data": total_required,
            "has_error_analysis": self.error_result is not None,
            "has_acquisition_plan": self.acquisition_result is not None,
            "has_impact_analysis": self.impact_result is not None
        }

    def __repr__(self):
        return (
            "DatasetIntelligence("
            f"path={self.path!r}, "
            f"model_available={self.model is not None}"
            ")"
        )